def qa_block() -> list[str]:
    """60 个题目 × 18 个方法族 × 3 种说法，再加两种问法。全部组合，不抽样。"""
    out = []
    n = len(QA_METHODS)
    for ti, topic in enumerate(QA_TOPICS):
        for k in range(n):
            m1 = QA_METHODS[k]
            m2 = QA_METHODS[(k + 5 + ti % 7) % n]
            for vi in range(3):
                tail = QA_TAIL[(ti + k + vi) % len(QA_TAIL)]
                second = "" if m1 is m2 else m2[(vi + 1) % 3]
                body = m1[vi] + second + tail
                asks = ("{t}怎么做？", "{t}该从哪下手？")
                for ask in asks[:1 + (k + ti) % 2]:
                    out.append(f"问：{ask.format(t=topic)}\n答：{body}")
    return out


